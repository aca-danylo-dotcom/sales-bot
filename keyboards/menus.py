"""Клавиатуры покупателя.

Постоянного меню под полем ввода у бота НЕТ, и это решение, а не упущение.
Четыре кнопки — «Каталог», «Корзина», «Мои заказы», «Доставка и оплата» —
делали из живого консультанта автомат с меню: человек первым делом искал
глазами нужную кнопку вместо того, чтобы спросить словами. Всё, что они
делали, ИИ умеет сам (см. services/ai_tools.py), а витрина открывается кнопкой
«Магазин» слева от поля ввода — её ставит bot.py и от этой клавиатуры она не
зависит.

Тексты кнопок остались КОНСТАНТАМИ: по ним хендлеры ловят прямые просьбы вроде
«корзина» или «мои заказы», написанные текстом. Такой ответ приходит мгновенно
и не стоит запроса к модели — см. фильтры в handlers/orders.py.
"""
from __future__ import annotations

from aiogram.types import ReplyKeyboardRemove

# Слова, на которые бот отвечает готовым разделом, а не через ИИ. Эмодзи в
# начале — наследство прежних кнопок: их всё ещё шлют те, у кого клавиатура
# осталась висеть с прошлых сессий. Сравнение идёт по очищенному тексту
# (см. handlers/orders.py), поэтому «Корзина» и «🧺 Корзина» — одно и то же.
BTN_CATALOG = "🛍 Каталог"
BTN_CART = "🧺 Корзина"
BTN_ORDERS = "📦 Мои заказы"
BTN_HELP = "❓ Доставка и оплата"


def _bare(text: str | None) -> str:
    """Оставляет от строки только буквы и пробелы: «🧺 Корзина» → «корзина»."""
    cleaned = "".join(
        char for char in (text or "").lower() if char.isalpha() or char.isspace()
    )
    return " ".join(cleaned.split())


def asks_for(text: str | None, button: str) -> bool:
    """Просит ли человек этот раздел прямо и целиком.

    Сравниваем всю реплику, а не ищем слово внутри: «положи в корзину вон те
    кроссовки» — работа для ИИ, он разберёт, что именно положить. А голое
    «корзина» — просьба показать её, и отвечать на неё запросом к модели значит
    платить за то, что и так лежит в базе.
    """
    return _bare(text) == _bare(button)


def main_menu() -> ReplyKeyboardRemove:
    """Убирает клавиатуру из-под поля ввода.

    Возвращает не пустоту, а именно снятие: на шагах оформления заказа
    появляются свои клавиатуры («Поделиться контактом», «Пропустить»), и после
    них поле ввода должно вернуться к обычному виду. Без явного снятия кнопка
    «Пропустить» осталась бы висеть до конца разговора.
    """
    return ReplyKeyboardRemove()
