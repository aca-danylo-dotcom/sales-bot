"""Клавиатуры покупателя.

Постоянного меню под полем ввода у бота НЕТ, и это решение, а не упущение.
Четыре кнопки — «Каталог», «Кошик», «Мої замовлення», «Доставка й оплата» —
делали из живого консультанта автомат с меню: человек первым делом искал
глазами нужную кнопку вместо того, чтобы спросить словами. Всё, что они
делали, ИИ умеет сам (см. services/ai_tools.py), а витрина открывается кнопкой
«Магазин» слева от поля ввода — её ставит bot.py и от этой клавиатуры она не
зависит.

Тексты кнопок остались КОНСТАНТАМИ: по ним хендлеры ловят прямые просьбы вроде
«кошик» или «мої замовлення», написанные текстом. Такой ответ приходит мгновенно
и не стоит запроса к модели — см. фильтры в handlers/orders.py.

Синонимы — обязательная часть: бот говорит по-украински, но добрая половина
покупателей пишет по-русски («корзина», «мои заказы»), и такая реплика должна
открывать тот же раздел, а не уходить в платную модель.
"""
from __future__ import annotations

from aiogram.types import ReplyKeyboardRemove

# Слова, на которые бот отвечает готовым разделом, а не через ИИ. Эмодзи в
# начале — наследство прежних кнопок: их всё ещё шлют те, у кого клавиатура
# осталась висеть с прошлых сессий. Сравнение идёт по очищенному тексту
# (см. _bare ниже), поэтому «Кошик» и «🧺 Кошик» — одно и то же.
BTN_CATALOG = "🛍 Каталог"
BTN_CART = "🧺 Кошик"
BTN_ORDERS = "📦 Мої замовлення"
BTN_HELP = "❓ Доставка й оплата"

# Как ещё называют тот же раздел. Русские варианты здесь не «на всякий случай»,
# а по факту переписки: магазин украинский, но пишут в него на двух языках.
_ALIASES: dict[str, tuple[str, ...]] = {
    BTN_CATALOG: ("каталог", "асортимент", "ассортимент"),
    BTN_CART: ("кошик", "корзина", "мій кошик", "моя корзина"),
    BTN_ORDERS: ("мої замовлення", "замовлення", "мои заказы", "заказы",
                 "мої покупки"),
    BTN_HELP: ("доставка й оплата", "доставка и оплата", "доставка та оплата",
               "доставка", "оплата"),
}


def _bare(text: str | None) -> str:
    """Оставляет от строки только буквы и пробелы: «🧺 Кошик» → «кошик»."""
    cleaned = "".join(
        char for char in (text or "").lower() if char.isalpha() or char.isspace()
    )
    return " ".join(cleaned.split())


def asks_for(text: str | None, button: str) -> bool:
    """Просит ли человек этот раздел прямо и целиком.

    Сравниваем всю реплику, а не ищем слово внутри: «поклади в кошик он ті
    кросівки» — работа для ИИ, он разберёт, что именно положить. А голое
    «кошик» — просьба показать его, и отвечать на неё запросом к модели значит
    платить за то, что и так лежит в базе.
    """
    asked = _bare(text)
    if not asked:
        return False
    return asked == _bare(button) or asked in _ALIASES.get(button, ())


def main_menu() -> ReplyKeyboardRemove:
    """Убирает клавиатуру из-под поля ввода.

    Возвращает не пустоту, а именно снятие: на шагах оформления заказа
    появляются свои клавиатуры («Поділитися контактом», «Пропустити»), и после
    них поле ввода должно вернуться к обычному виду. Без явного снятия кнопка
    «Пропустити» осталась бы висеть до конца разговора.
    """
    return ReplyKeyboardRemove()
