"""Форматирование значений для сообщений клиенту.

Живёт отдельно, потому что одни и те же цены и подписи вариантов показывают
и карточки товаров (handlers/client.py), и корзина с заказами
(handlers/orders.py). Дублировать формат нельзя: «1200 грн» в карточке и
«1 200.00 грн» в корзине выглядят как разные цены одного товара.
"""
from __future__ import annotations

import re

import config

# Имя получателя: буквы, пробел, дефис и апостроф — всё, что бывает в «Анна-Мария
# О'Коннор». Цифры, @, ссылки и эмодзи в имени означают, что человек написал в
# поле имени что-то другое: ник, адрес или отговорку.
_NAME_ALLOWED_RE = re.compile(r"^[^\W\d_]+(?:[ \-'’][^\W\d_]+)*$", re.UNICODE)
_VOWELS = set("аеёиоуыэюяіїєaeiouy")
# Апостроф — часть слова («О'Коннор», «Мар'я»), а не разделитель: делить по нему
# нельзя, иначе «я» и «О» превращаются в слова из одной буквы и имя не проходит.
_NAME_SPLIT_RE = re.compile(r"[ \-]+")
# Отговорки на месте имени и строки, набранные по клавиатуре: в накладную такое
# писать нельзя, а гласные в них есть — одной проверкой гласных не отсеются.
_NOT_NAMES = {
    "нет", "нету", "незнаю", "неважно", "пофиг", "какразница", "любое", "тест",
    "test", "аноним", "яяя", "ктото", "никто", "какобычно", "самзнаешь", "покупатель",
    "asd", "asdf", "asdfg", "asdasd", "qwe", "qwer", "qwerty", "фыв", "фыва",
    "фывап", "йцу", "йцук", "йцукен", "ыва", "zxc", "zxcv",
}
_MAX_NAME_WORDS = 4


def money(value: float) -> str:
    """Цена так, как её читает человек: 1 200 грн, без хвоста ,00."""
    rounded = round(float(value), 2)
    text = f"{rounded:,.0f}" if rounded == int(rounded) else f"{rounded:,.2f}"
    return f"{text.replace(',', ' ')} {config.SHOP_CURRENCY}"


def plural(count: int, one: str, few: str, many: str) -> str:
    """Русское склонение после числа: 1 заказ, 2 заказа, 5 заказов.

    Нужно там, где число подставляется в текст: «3 заказов» на видном месте
    читается как небрежность, будто цифру никто не смотрел.
    """
    tail, hundred = count % 10, count % 100
    if tail == 1 and hundred != 11:
        return one
    if 2 <= tail <= 4 and not 12 <= hundred <= 14:
        return few
    return many


def looks_like_name(text: str | None) -> bool:
    """Похоже ли это на настоящее имя получателя.

    Проверка нужна и боту на шаге оформления, и ИИ перед записью имени в профиль:
    по этому имени курьер ищет человека в отделении, а «asdf», «ник в телеграме»
    или «не знаю» посылку никому не выдадут. Требуем немного: только буквы (с
    дефисом и апострофом), хотя бы одну гласную в каждом слове, не больше четырёх
    слов. Редкое имя, транслит и украинские буквы проходят — отсекается мусор.
    """
    value = " ".join((text or "").split())
    if not 2 <= len(value) <= 60 or not _NAME_ALLOWED_RE.match(value):
        return False

    words = _NAME_SPLIT_RE.split(value.lower())
    if len(words) > _MAX_NAME_WORDS:
        return False
    if "".join(words) in _NOT_NAMES or any(word in _NOT_NAMES for word in words):
        return False
    return all(
        # Гласная в каждом слове: «Кшиштоф» проходит, «джджд» — нет.
        len(word) >= 2 and (set(word) & _VOWELS)
        # И хотя бы две разные буквы, без трёх одинаковых подряд: «ааааа» — не имя.
        and len(set(word)) > 1 and not re.search(r"(.)\1\1", word)
        for word in words
    )


# Из номера выбрасываем всё, кроме цифр и плюса: скобки, дефисы и пробелы
# человек ставит как привык, а курьеру нужен один вид записи.
_PHONE_CLEAN_RE = re.compile(r"[^\d+]")


def clean_phone(text: str) -> str | None:
    """Нормализует номер к виду +380XXXXXXXXX. None — если это не телефон.

    Лежит здесь, а не в оформлении заказа, потому что номер теперь приходит с
    двух сторон: из чата (кнопка «Поделиться контактом» или руками) и из
    мини-приложения. Записать их по-разному нельзя — в карточке заказа это
    выглядело бы как два разных клиента.
    """
    cleaned = _PHONE_CLEAN_RE.sub("", text or "")
    plus = cleaned.startswith("+")
    digits = cleaned.lstrip("+").replace("+", "")
    if not digits.isdigit():
        return None

    if not plus:
        # Локальные записи украинских номеров: 0XXXXXXXXX и 80XXXXXXXXX
        if len(digits) == 10 and digits.startswith("0"):
            digits = "38" + digits
        elif len(digits) == 11 and digits.startswith("80"):
            digits = "3" + digits
    if not 10 <= len(digits) <= 15:
        return None
    return "+" + digits


# Отделение Новой Почты всегда с номером: «12», «№12», «Поштомат 4521».
# Без цифры это не адрес доставки, а фраза вроде «как обычно» или «на твоё
# усмотрение» — по такой строке посылку не отправить.
_BRANCH_DIGIT_RE = re.compile(r"\d")


def looks_like_branch(text: str | None) -> bool:
    """Похоже ли это на отделение почты — то есть есть ли в строке номер."""
    return bool(_BRANCH_DIGIT_RE.search(text or ""))


def variant_label(variant: dict) -> str:
    """«12 oz / чёрный», «42», «чёрный» — то из размера и цвета, что заполнено."""
    parts = [part for part in (variant.get("size"), variant.get("color")) if part]
    return " / ".join(parts) if parts else "один варіант"


