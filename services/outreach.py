"""Напоминания, которые магазин пишет первым.

Поводов два: корзина, которую бросили, и человек, который поговорил и пропал.
Каналов тоже два: Telegram (есть у всех) и почта (только если клиент оставил
адрес сам). Скидка — именной одноразовый промокод, размер и срок берутся из
настроек (PROMO_PERCENT, PROMO_TTL_DAYS); нулевой процент выключает скидку, и
тогда уходит просто напоминание.

ГЛАВНОЕ ЗДЕСЬ — ТЕКСТ НЕ ШАБЛОННЫЙ. Его пишет та же модель, что ведёт разговор
в чате, и пишет каждый раз заново: под конкретного человека, под то, что лежит
у него в корзине, и под то, сколько времени прошло. Шаблонная рассылка узнаётся
с первой строки и уходит в игнор — ровно поэтому её и просили заменить.

Три вещи, которые здесь сделаны нарочно и на которые стоит смотреть при правках:

1. У текста от модели есть запасной вариант. Провайдер лежит, кончился лимит,
   ответ пришёл пустым — напоминание всё равно уходит, просто обычными словами.
   Молчать вместо письма нельзя: задача выполняется раз в сутки, и «в другой
   раз» здесь значит «никогда».

2. Модель НЕ придумывает условия. Промокод, процент и срок подставляются кодом
   после неё — в промпте прямо сказано не называть числа. Иначе однажды клиенту
   пообещают «минус 30% и бесплатную доставку», и это придётся выполнять.

3. Отправляем обычным текстом, без разметки Telegram. Текст пишет модель, и
   любая скобка или знак «меньше» в нём превратили бы разметку в ошибку
   отправки — сообщение бы просто не ушло.
"""
from __future__ import annotations

import logging

import config
from db import queries
from services import ai, mail
from services.format import money, variant_label

logger = logging.getLogger(__name__)

# Сколько слов разрешаем модели. Напоминание длиннее пяти строк не читают.
_MAX_CHARS = 420

_STYLE = (
    "Ти — менеджер магазину «{shop}» ({city}). Пиши покупцеві коротке особисте "
    "повідомлення в месенджер: 2–4 речення, живою розмовною мовою, на «ви», "
    "без канцеляриту й без рекламних вигуків.\n\n"
    "МОВА: тільки українська, кожне слово. Хоч би якою мовою людина писала "
    "раніше — відповідь українською.\n\n"
    "ЗАБОРОНЕНО:\n"
    "— називати себе ботом, ШІ чи асистентом;\n"
    "— писати будь-які числа: відсотки, суми, строки, розміри знижок. Про знижку "
    "й строк нижче допише магазин окремим рядком — якщо ти назвеш свої числа, "
    "вони розійдуться зі справжніми;\n"
    "— обіцяти бронь товару, безкоштовну доставку, подарунки й будь-які умови, "
    "яких немає в завданні;\n"
    "— починати зі слів «Вітаю!» і «Доброго дня!» — це лист у чат, де ви вже "
    "спілкувалися;\n"
    "— слова «акція», «унікальна пропозиція», «поспішайте», «тільки сьогодні».\n\n"
    "Пиши так, ніби згадав про цю людину й вирішив написати сам. "
    "У відповідь дай ТІЛЬКИ текст повідомлення, без пояснень і лапок."
)


def _cart_lines(cart: dict) -> str:
    """Состав корзины простым текстом — его же увидит клиент."""
    return "\n".join(
        f"• {item['title']} ({variant_label(item)}) — {item['qty']} шт"
        for item in cart["items"]
    )


async def _write(task: str) -> str | None:
    """Просит модель написать текст. None — не получилось, берите запасной.

    Инструментов не даём вовсе: здесь не разговор, а одна реплика, и лазить в
    каталог модели незачем — всё нужное уже в задании.
    """
    conversation: list[dict] = [{"role": "user", "content": task}]
    try:
        text = await ai.run_agent(
            instructions=_STYLE.format(shop=config.SHOP_NAME, city=config.SHOP_CITY),
            conversation=conversation,
            tools=[],
            tool_executor=_no_tools,
            max_iterations=1,
        )
    except Exception as exc:
        # Сюда попадает и ProviderUnavailable, и всё остальное: напоминание
        # важнее причины, по которой модель промолчала.
        logger.warning("Текст напоминания не сгенерирован: %s", exc)
        return None

    text = (text or "").strip().strip('"')
    if not text or len(text) > _MAX_CHARS * 2:
        return None
    return text[:_MAX_CHARS]


async def _no_tools(name: str, arguments: dict) -> str:  # noqa: ARG001
    """Инструментов в этом режиме нет — заглушка на случай, если модель попросит."""
    return '{"error": "no_tools"}'


def _promo_line(promo: dict | None) -> str:
    """Строка про скидку — её пишет код, а не модель (см. правило 2 в шапке)."""
    if not promo:
        return ""
    return (
        f"\nВаш промокод на знижку {promo['percent']}%: {promo['code']} "
        f"(діє до {promo['expires_date']}).\n"
        f"Надішліть його сюди — і знижка застосується до замовлення."
    )


async def cart_reminder(client: dict | None, cart: dict, promo: dict | None) -> str:
    """Текст напоминания о брошенной корзине."""
    name = (client or {}).get("name") or ""
    task = (
        f"Покупець{f' на ім\'я {name}' if name else ''} зібрав кошик і не "
        f"оформив замовлення, минуло кілька годин. Нагадай про нього й м'яко "
        f"запропонуй оформити. Ось що лежить у кошику:\n{_cart_lines(cart)}\n\n"
        f"Товар не заброньовано — якщо доречно, скажи про це однією фразою, але "
        f"не лякай."
    )
    written = await _write(task)
    if not written:
        written = (
            "Ваш кошик усе ще чекає — я його зберіг. Товар не заброньовано, "
            "залишок спільний, тож якщо все ще потрібно, давайте оформимо 🙂"
        )

    return (
        f"{written}\n\n"
        f"У кошику:\n{_cart_lines(cart)}\n"
        f"Сума: {money(cart['total'])}"
        f"{_promo_line(promo)}"
    )


async def winback(client: dict | None, promo: dict | None) -> str:
    """Текст тому, кто давно не заходил."""
    name = (client or {}).get("name") or ""
    task = (
        f"Покупець{f' на ім\'я {name}' if name else ''} писав нам у магазин, але "
        f"давно нічого не замовляв і зник. Напиши йому коротко: без натиску, "
        f"по-людськи — що будемо раді допомогти з підбором, якщо він усе ще "
        f"придивляється до чогось. Нічого не випрошуй."
    )
    written = await _write(task)
    if not written:
        written = (
            "Давно вас не було — якщо все ще придивляєтеся до екіпірування, "
            "напишіть, що потрібно, і я підберу під ваш розмір."
        )
    return f"{written}{_promo_line(promo)}"


async def make_promo(client_id: int, reason: str) -> dict | None:
    """Выписывает клиенту код по настройкам магазина. None — скидки выключены."""
    return await queries.create_promo_code(
        client_id,
        percent=config.PROMO_PERCENT,
        ttl_days=config.PROMO_TTL_DAYS,
        reason=reason,
    )


async def send_email_copy(client: dict | None, subject: str, text: str) -> bool:
    """Копия напоминания на почту — если клиент оставлял адрес.

    Отписка приписывается к каждому письму: адрес человек дал добровольно и
    забрать его обратно должен так же просто.
    """
    address = (client or {}).get("email") or ""
    if not address or not mail.is_enabled():
        return False

    body = (
        f"{text}\n\n"
        f"—\n{config.SHOP_NAME}\n"
        f"Цей лист надійшов, бо ви залишили пошту в нашому боті. "
        f"Щоб більше не отримувати листів, надішліть боту команду /email off."
    )
    return await mail.send(address, subject, body)
